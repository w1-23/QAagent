"""Agent adapter for research figures.

Two tools, one engine.

``create_research_figure``
    The declarative path. The model describes a figure — chart type, which
    columns to plot, how to group them, what the axes mean — and the
    *service* writes the plotting code from that description. The code is
    generated by the service, not supplied by the caller, so this path has
    no execution risk and works on any deployment.

``run_research_figure_script``
    The free-script path. The model supplies Python that draws the figure.
    That code is untrusted, so it runs in the one-shot sandbox and nowhere
    else. When no sandbox is configured, this tool is not offered at all
    (see ``tool_availability``), rather than being offered and then failing.

What the user gets
------------------
The figure, not the script. The generated code is registered in the
account's file library so the work is reproducible and auditable, but the
answer shows the picture and a link to the workspace where it can be
adjusted — the code itself is not pasted into the conversation.

The invariant both paths keep
------------------------------
The preview and the download are the same bytes. Both come from one
render; there is no second drawing step and no client-side rewriting. A
figure that looks one way in the chat bubble looks exactly the same way in
the file the user downloads.
"""
from __future__ import annotations

import json
from typing import Any

from langchain_core.tools import tool

from src.core.tool_errors import ToolArgumentError

# The formats a figure project carries. SVG is the primary one because its
# text stays real text; PNG and PDF are what a journal asks for.
FIGURE_FORMATS = ("svg", "png", "pdf")

# The MIME type of each format.
MIME_BY_FORMAT = {
    "svg": "image/svg+xml",
    "png": "image/png",
    "pdf": "application/pdf",
}

# A script longer than this is not a figure script; it is a program.
_MAX_SCRIPT_CHARS = 200_000


def _json_arg(raw: Any, name: str) -> Any:
    """Accept either a JSON string or an already-decoded value."""
    if raw is None or raw == "":
        return None
    if isinstance(raw, (dict, list, tuple)):
        return raw
    if isinstance(raw, str):
        try:
            return json.loads(raw)
        except (TypeError, ValueError):
            raise ToolArgumentError(
                f"{name} 需要 JSON 文本；例如 {{\"chart\": \"bar\"}}。") from None
    raise ToolArgumentError(f"{name} 需要 JSON 文本。")


def _owner() -> int:
    from src.core.tracing import get_user_id
    return int(get_user_id() or 0)


def _session() -> str:
    from src.core.tracing import get_session_id
    return str(get_session_id() or "")


def _error(code: str, message: str) -> tuple[str, dict]:
    """A failed tool call, in the shape the executor reports.

    The reason code is what the execution ledger records, so it names the
    *kind* of failure rather than repeating the message.
    """
    result = {
        "error": message,
        "_tool_outcome": {"status": "failed", "reason_code": code, "artifacts": []},
    }
    return f"[FIGURE_{code}] {message}", result


def _publish(filename: str, payload: bytes, mime: str) -> dict[str, Any]:
    """Publish one file into the account library and describe it.

    The bytes that are stored are the bytes that were produced. The
    registration is verified against the stored file's digest before the
    link is handed back, so a link always points at the content the caller
    produced.
    """
    from src.research.tools import _save_artifact
    from src.session import files as session_files

    url = _save_artifact(filename, payload, mime)
    artifact_id = url.rsplit("/", 1)[-1]
    entries = session_files.list_files(_session(), _owner())
    entry = next((item for item in entries
                  if item.get("artifact_id") == artifact_id), None)
    if not entry:
        raise ToolArgumentError("产物已生成，但资料库登记失败。")
    return {
        "artifact_id": artifact_id,
        "file_id": entry.get("file_id", ""),
        "filename": entry.get("filename", filename),
        "sha256": entry.get("sha256", ""),
        "size": entry.get("size_bytes", len(payload)),
        "download_url": entry.get("download_url", ""),
        "artifact_url": url,
    }


def _register_figure(svg_bytes: bytes, alt_text: str) -> str:
    """Register the figure for the chat inline preview.

    The existing figure registry turns a rendered SVG into the
    ``[[FIGURE:n]]`` placeholder that the chat expands into an inline
    preview. The SVG here has already been flattened into the plain subset
    the browser renderer accepts, so the inline preview and the downloaded
    file are the same drawing.
    """
    from src.core.figures import register
    return register(svg_bytes.decode("utf-8", "replace"), alt_text)


def _load_account_table(file_id: str) -> Any:
    """Read a table from the account library.

    The account file is fetched with the ownership check the library
    already performs, so a file belonging to another account cannot be
    read by naming its id.
    """
    from src.session import files as session_files

    entry = session_files.get_account_file(str(file_id), _owner())
    if not entry:
        raise ToolArgumentError("资料库中没有该文件，或该文件不属于当前账号。")
    return entry


def _resolve_columns(spec: dict[str, Any]) -> tuple[Any, dict[str, Any]]:
    """Turn the specification's references into a resolved figure.

    The references point at this turn's attachments, at the account
    library, or carry their values inline. Whichever they are, the result
    is a :class:`ResolvedFigure`: plain numbers and labels, with no file
    handles and no column names the renderer would have to look up.
    """
    from src.figures.resolve import resolve_spec
    return resolve_spec(spec)


@tool(response_format="content_and_artifact")
def create_research_figure(
    spec_json: str = "",
    title: str = "",
    formats_json: str | list[str] = "",
    output_name: str = "",
) -> tuple[str, dict]:
    """用受校验的图规格生成科研图（SVG/PNG/PDF），并登记进账号资料库。

    spec_json 是图规格的 JSON 文本，例如：
    {"chart": "bar", "title": "果实重量", "x_label": "处理", "y_label": "g",
     "x": {"kind": "inline", "column": "处理", "values": ["CK", "T1"]},
     "y": {"kind": "inline", "column": "重量", "values": [10.1, 12.2]},
     "group": {"kind": "inline", "column": "时间", "values": ["7d", "7d"]},
     "error": "sd", "style": {"palette": "nature", "font_size": 7}}

    chart：bar / line / scatter / errorbar / boxplot / histogram。
    数据引用 kind：attachment（本轮上传的表，按列名取）、account_file（资料库
    file_id + 列名）、inline（直接给 values，≤200 行）。
    error：none / sd / se / ci95 —— 误差棒的含义，必须与数据实际算出的量一致。
    formats_json：需要的格式，默认 svg+png+pdf。
    output_name：文件名（不含扩展名），默认用标题。

    图由服务端根据规格生成，不执行任何调用方代码。误差棒与统计量必须来自
    真实计算好的数据，不得臆造。
    """
    try:
        raw_spec = _json_arg(spec_json, "spec_json")
        if not isinstance(raw_spec, dict):
            raise ToolArgumentError(
                "spec_json 需要是 JSON 对象，例如 {\"chart\": \"bar\"}。")
        if title:
            raw_spec = dict(raw_spec)
            raw_spec.setdefault("title", title)
        formats = _json_arg(formats_json, "formats_json") or list(FIGURE_FORMATS)
        if isinstance(formats, str):
            formats = [formats]
        formats = [str(item).strip().lower() for item in formats
                   if str(item).strip().lower() in FIGURE_FORMATS]
        if not formats:
            formats = ["svg"]
    except ToolArgumentError as exc:
        return _error("ARG", str(exc))

    from src.figures.spec import SpecError, parse_spec
    try:
        spec = parse_spec(raw_spec)
        resolved, source_info = _resolve_columns(spec)
    except SpecError as exc:
        return _error("SPEC", exc.message)
    except Exception as exc:  # noqa: BLE001 - report, never crash the turn
        return _error("DATA", f"数据解析失败：{exc}")

    from src.figures.core import build_resolved_figure
    from src.figures.exporter import ExportError, export_all
    from src.figures.manifest import build_manifest

    try:
        rendered = build_resolved_figure(resolved)
        blobs = export_all(rendered, formats=tuple(formats), dpi=resolved.style.dpi)
        manifest = build_manifest(rendered, source="spec")
    except (SpecError, ExportError) as exc:
        return _error("RENDER", str(getattr(exc, "message", exc)))
    except Exception as exc:  # noqa: BLE001
        return _error("RENDER", f"出图失败：{exc}")

    stem = output_name or resolved.title or "figure"
    published: list[dict[str, Any]] = []
    for fmt in formats:
        payload = blobs.get(fmt)
        if payload is None:
            continue
        try:
            entry = _publish(f"{stem}.{fmt}", payload, MIME_BY_FORMAT[fmt])
        except Exception as exc:  # noqa: BLE001
            return _error("PUBLISH", f"{fmt} 交付失败：{exc}")
        published.append({"format": fmt, **entry})

    svg_bytes = blobs.get("svg")
    placeholder = ""
    if svg_bytes:
        try:
            placeholder = _register_figure(
                svg_bytes, resolved.title or "科研图件")
        except Exception:
            placeholder = ""

    project = _record_project(
        title=resolved.title or stem, source_kind="spec",
        source=spec.as_dict(), manifest=manifest, exports=published,
        data_refs=source_info.get("refs", []))
    if project:
        published.append({"format": "project", "figure_id": project["figure_id"],
                          "workspace_url": f"/figures?project={project['figure_id']}"})

    summary = {
        "figure_id": project["figure_id"] if project else "",
        "chart": resolved.chart,
        "title": resolved.title,
        "objects": len(manifest.get("objects", [])),
        "exports": published,
        "figure_placeholder": placeholder,
        "note": "图内微调在「图表工作台」完成（/figures），可改颜色、字号、线宽与位置；"
                "数据值与统计量不可更改。",
    }
    summary["_tool_outcome"] = {
        "status": "complete",
        "reason_code": "figure_published",
        "artifacts": [item["artifact_url"] for item in published
                      if item.get("artifact_url")],
    }
    return json.dumps(summary, ensure_ascii=False, default=str), summary


@tool(response_format="content_and_artifact")
def run_research_figure_script(
    script: str = "",
    title: str = "",
    formats_json: str | list[str] = "",
    output_name: str = "",
) -> tuple[str, dict]:
    """在一次性沙箱里执行自定义绘图脚本，产出科研图（SVG/PNG/PDF）。

    仅在服务端已配置 Docker 沙箱时可用；未配置时本工具不会出现。
    脚本必须：使用 matplotlib（Agg 后端）、最后留下恰好一张 Figure、
    不联网、不创建子进程、不访问沙箱以外的文件。

    script 是完整的 Python 源码，例如：
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(7, 5))
    ax.bar(['CK', 'T1'], [10.1, 12.2], color='#0F4D92', label='果实重量')
    ax.set_ylabel('g'); ax.set_title('果实重量')

    formats_json：需要的格式，默认 svg+png+pdf。
    output_name：文件名（不含扩展名）。

    失败时返回 [FIGURE_...] 形式的说明，指出问题与改法；沙箱不会执行任何
    需要网络或特权的操作。
    """
    from src.figures.sandbox import SandboxJob, SandboxUnavailable, select_backend
    from src.config import settings

    text = str(script or "")
    if not text.strip():
        return "[FIGURE_ARG] script 不能为空。", {}
    if len(text) > _MAX_SCRIPT_CHARS:
        return (f"[FIGURE_ARG] 脚本超过 {_MAX_SCRIPT_CHARS} 字符上限，"
                "请精简后重试。"), {}

    try:
        formats = _json_arg(formats_json, "formats_json") or list(FIGURE_FORMATS)
        if isinstance(formats, str):
            formats = [formats]
        formats = [str(item).strip().lower() for item in formats
                   if str(item).strip().lower() in FIGURE_FORMATS]
        if not formats:
            formats = ["svg"]
    except ToolArgumentError as exc:
        return _error("ARG", str(exc))

    runner = select_backend(
        backend=str(getattr(settings, "FIGURES_SANDBOX_BACKEND", "") or ""),
        image=str(getattr(settings, "FIGURES_SANDBOX_IMAGE", "") or ""),
        runtime=str(getattr(settings, "FIGURES_SANDBOX_RUNTIME", "") or ""),
        allow_local=bool(getattr(settings, "FIGURES_SANDBOX_ALLOW_LOCAL", False)))
    if runner is None:
        return _error("SANDBOX_UNAVAILABLE",
                      "当前环境没有配置绘图脚本沙箱，无法执行自定义绘图脚本；"
                      "请改用声明式图件工具 create_research_figure。")

    outputs = {fmt: f"figure.{fmt}" for fmt in formats}
    job = SandboxJob(
        script=text,
        outputs=outputs,
        timeout_sec=int(getattr(settings, "FIGURES_SANDBOX_TIMEOUT_SEC", 120) or 120),
        memory_mb=int(getattr(settings, "FIGURES_SANDBOX_MEMORY_MB", 1024) or 1024),
        cpus=str(getattr(settings, "FIGURES_SANDBOX_CPUS", "1.0") or "1.0"),
        image=str(getattr(settings, "FIGURES_SANDBOX_IMAGE", "") or ""),
        runtime=str(getattr(settings, "FIGURES_SANDBOX_RUNTIME", "") or ""))
    try:
        result = runner.run(job)
    except SandboxUnavailable as exc:
        return _error("SANDBOX_UNAVAILABLE", str(exc))
    except Exception as exc:  # noqa: BLE001
        return _error("SANDBOX_ERROR", f"沙箱执行失败：{exc}")

    if not result.ok:
        message = result.describe() or "[FIGURE_SCRIPT_ERROR] 绘图脚本执行失败。"
        code = {"timeout": "SCRIPT_TIMEOUT", "oom": "SCRIPT_OOM",
                "forbidden": "SCRIPT_FORBIDDEN",
                "output": "SCRIPT_OUTPUT"}.get(result.failure_kind, "SCRIPT_ERROR")
        return _error(code, message)

    stem = output_name or title or "figure"
    published: list[dict[str, Any]] = []
    for fmt in formats:
        payload = result.outputs.get(fmt)
        if payload is None:
            continue
        try:
            entry = _publish(f"{stem}.{fmt}", payload, MIME_BY_FORMAT[fmt])
        except Exception as exc:  # noqa: BLE001
            return _error("PUBLISH", f"{fmt} 交付失败：{exc}")
        published.append({"format": fmt, **entry})

    manifest: dict[str, Any] = {}
    try:
        manifest = json.loads(result.stdout or "{}").get("manifest") or {}
    except (TypeError, ValueError):
        manifest = {}

    placeholder = ""
    svg_bytes = result.outputs.get("svg")
    if svg_bytes:
        try:
            placeholder = _register_figure(svg_bytes, title or "科研图件")
        except Exception:
            placeholder = ""

    project = _record_project(
        title=title or stem, source_kind="script",
        source={"script": text}, manifest=manifest, exports=published)
    if project:
        published.append({"format": "project", "figure_id": project["figure_id"],
                          "workspace_url": f"/figures?project={project['figure_id']}"})

    summary = {
        "figure_id": project["figure_id"] if project else "",
        "title": title or stem,
        "objects": len(manifest.get("objects", [])),
        "exports": published,
        "figure_placeholder": placeholder,
        "backend": result.backend,
        "duration_ms": result.duration_ms,
        "note": "图内微调在「图表工作台」完成（/figures）。",
    }
    summary["_tool_outcome"] = {
        "status": "complete",
        "reason_code": "figure_published",
        "artifacts": [item["artifact_url"] for item in published
                      if item.get("artifact_url")],
    }
    return json.dumps(summary, ensure_ascii=False, default=str), summary


def _record_project(*, title: str, source_kind: str, source: Any,
                    manifest: dict[str, Any], exports: list[dict[str, Any]],
                    data_refs: list[Any] | None = None) -> dict[str, Any]:
    """Save the project so the workspace can reopen and edit it."""
    from src.figures import store

    owner = _owner()
    if not owner:
        return {}
    try:
        project = store.create_project(
            owner_user_id=owner, title=title, source_kind=source_kind,
            source=source, session_id=_session(), data_refs=data_refs or [])
        export_map = {item["format"]: item for item in exports
                      if item.get("format") in FIGURE_FORMATS}
        store.update_project(
            project["figure_id"], owner,
            manifest_json=manifest, exports_json=export_map,
            render_version=1)
        project["manifest_json"] = manifest
        project["exports_json"] = export_map
        return project
    except Exception:
        return {}


__all__ = ["create_research_figure", "run_research_figure_script"]
